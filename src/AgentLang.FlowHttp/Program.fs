module AgentLang.FlowHttp.Program

open System
open System.IO
open System.Text
open AgentLang.Llvm

let private usage =
    "usage: AgentLang.FlowHttp emit --app <name> --source <file.flow> [--source ...] --target windows-x64|linux-x64 [--profile trusted|diagnostic] [--unverified] [--schema <schema.sql>] --out <dir>"

/// emit: compiles the stdlib and app sources and writes <out>/module.ll (the
/// two-entry owning module for the target), <out>/diagnostics.tsv and <out>/symbols.tsv
/// (agentlang_word_NNNN -> Flow word, for profilers). --unverified skips the commit, so
/// no attached test runs (the code is still type-checked and IR-verified), and writes
/// <out>/UNVERIFIED.txt; a later emit without it is the verification step.
/// --schema checks every SQL literal against the app's schema (SqlCheck) before
/// anything else. <out>/flow_app_schema.c holds the canonical schema text (empty
/// without --schema), which the native host compares with the database it opens.
let private emit (args: string list) =
    let mutable app = ""
    let mutable target = OwningTarget.WindowsX64
    let mutable profile = OwningRuntimeProfile.TrustedGenerated
    let mutable out = ""
    let mutable verify = true
    let mutable schema = ""
    let sources = ResizeArray<string>()
    let rec parse = function
        | "--app" :: value :: rest -> app <- value; parse rest
        | "--source" :: value :: rest -> sources.Add(Path.GetFullPath value); parse rest
        | "--target" :: value :: rest -> target <- OwningTarget.Parse value; parse rest
        | "--profile" :: "trusted" :: rest -> profile <- OwningRuntimeProfile.TrustedGenerated; parse rest
        | "--profile" :: "diagnostic" :: rest -> profile <- OwningRuntimeProfile.Diagnostic; parse rest
        | "--out" :: value :: rest -> out <- Path.GetFullPath value; parse rest
        | "--unverified" :: rest -> verify <- false; parse rest
        | "--schema" :: value :: rest -> schema <- Path.GetFullPath value; parse rest
        | [] -> ()
        | other :: _ -> failwith $"Unknown argument {other}. {usage}"
    parse args
    if app = "" || sources.Count = 0 || out = "" then failwith usage
    Directory.CreateDirectory out |> ignore
    let schemaSource = Path.Combine(out, "flow_app_schema.c")
    if schema <> "" then
        let checkedSql =
            FlowApp.timed "sql-check" (fun () ->
                SqlCheck.run schema [ for path in sources -> path, File.ReadAllText path ] 256)
        match checkedSql.Errors with
        | [] -> ()
        | errors -> failwith $"""SQL does not match {Path.GetFileName schema}:{Environment.NewLine}  {String.Join(Environment.NewLine + "  ", errors)}"""
        File.WriteAllText(
            schemaSource,
            "/* Generated by AgentLang.FlowHttp emit --schema " + Path.GetFileName schema + " (SHA-256 " + checkedSql.SchemaHash + "): the canonical
"
            + " * schema (SqlCheck.canonicalQuery) the server must find in the database it opens. */
"
            + "const char flow_app_schema[] = \"" + SqlCheck.cLiteral checkedSql.SchemaText + "\";
",
            UTF8Encoding(false))
        printfn "sql: %d calls, %d distinct statements checked against %s (SQLite %s); schema %s" checkedSql.Checked checkedSql.Statements (Path.GetFileName schema) checkedSql.SqliteVersion (checkedSql.SchemaHash.Substring(0, 12))
    else
        File.WriteAllText(schemaSource, "/* Generated by AgentLang.FlowHttp emit without --schema: no schema check. */
const char flow_app_schema[] = \"\";
", UTF8Encoding(false))
    let project = Path.Combine(out, "engine-" + Guid.NewGuid().ToString("N").Substring(0, 8))
    // The build never runs requests; its production provider is a scratch database.
    use flowApp = FlowApp.loadWith verify project app (List.ofSeq sources) ":memory:" 0
    if verify && not (isNull (Environment.GetEnvironmentVariable "AGENTLANG_BUILD_ADD_PROBE")) then
        // How long adding one function takes once the project is loaded: define a word
        // with its attached test, then commit that word alone.
        let request (operation: string) (fields: (string * System.Text.Json.Nodes.JsonNode) list) =
            let args = System.Text.Json.Nodes.JsonObject()
            for key, value in fields do args[key] <- value
            let response = flowApp.Engine.Dispatch(operation, args)
            if not (response["ok"].GetValue<bool>()) then failwith $"probe {operation}: {response.ToJsonString()}"
            response
        let source = "fn probe.add-one(n: Int) -> Int {\n    n + 1\n}\n\ntest probe.add-one/two {\n    expect probe.add-one(1) == 2\n}\n"
        FlowApp.timed "probe-define" (fun () ->
            request "define" [ "frontend", System.Text.Json.Nodes.JsonValue.Create("flow"); "syntaxVersion", System.Text.Json.Nodes.JsonValue.Create(2); "source", System.Text.Json.Nodes.JsonValue.Create(source) ] |> ignore)
        let committed = FlowApp.timed "probe-commit" (fun () -> request "commit" [ "word", System.Text.Json.Nodes.JsonValue.Create("probe.add-one") ])
        // Commit lists the attached tests it ran and passed; the probe's own test must be one.
        let passed = committed["data"].AsArray() |> Seq.map (fun item -> item.GetValue<string>()) |> Set.ofSeq
        if not (passed.Contains "probe.add-one/two") then failwith $"probe commit did not run probe.add-one/two: {committed.ToJsonString()}"
        // Replacing a word with a caller: the caller's tests must run too.
        let flow2 (source: string) = [ "frontend", System.Text.Json.Nodes.JsonValue.Create("flow") :> System.Text.Json.Nodes.JsonNode; "syntaxVersion", System.Text.Json.Nodes.JsonValue.Create(2); "source", System.Text.Json.Nodes.JsonValue.Create(source) ]
        request "define" (flow2 "fn probe.twice(n: Int) -> Int {\n    probe::add-one(probe::add-one(n))\n}\n\ntest probe.twice/two {\n    probe::twice(2)\n    => 4\n}\n") |> ignore
        request "commit" [ "word", System.Text.Json.Nodes.JsonValue.Create("probe.twice") ] |> ignore
        let described = request "describe" [ "word", System.Text.Json.Nodes.JsonValue.Create("probe.add-one") ]
        let revision = (described["data"]["revision"]).GetValue<int>()
        FlowApp.timed "probe-replace-define" (fun () ->
            request "define" (flow2 "fn probe.add-one(n: Int) -> Int {\n    1 + n\n}\n" @ [ "replace", System.Text.Json.Nodes.JsonValue.Create(true); "expectedRevision", System.Text.Json.Nodes.JsonValue.Create(revision) ]) |> ignore)
        let replaced = FlowApp.timed "probe-replace-commit" (fun () -> request "replace-word" [ "word", System.Text.Json.Nodes.JsonValue.Create("probe.add-one") ])
        let replacedTests = replaced["data"].AsArray() |> Seq.map (fun item -> item.GetValue<string>()) |> Set.ofSeq
        if not (replacedTests.Contains "probe.twice/two") then failwith $"probe replacement did not run the caller's test: {replaced.ToJsonString()}"
    let ir, diagnostics = FlowApp.timed "emit-native" (fun () -> FlowApp.emitNative flowApp profile target)
    File.WriteAllText(Path.Combine(out, "module.ll"), ir, UTF8Encoding(false))
    File.WriteAllText(Path.Combine(out, "diagnostics.tsv"), FlowApp.diagnosticsText diagnostics, UTF8Encoding(false))
    File.WriteAllText(Path.Combine(out, "symbols.tsv"), FlowApp.nativeSymbolsText flowApp, UTF8Encoding(false))
    let marker = Path.Combine(out, "UNVERIFIED.txt")
    if verify then File.Delete marker
    else File.WriteAllText(marker, "Built without running attached tests (emit --unverified). Rebuild without -Unverified to verify.\n", UTF8Encoding(false))
    try Directory.Delete(project, true) with _ -> ()
    printfn "emitted %s (%s, %s, context %s%s)" (Path.Combine(out, "module.ll")) target.Triple (if profile = OwningRuntimeProfile.TrustedGenerated then "trusted" else "diagnostic") flowApp.ContextType (if verify then "" else ", UNVERIFIED: attached tests not run")

[<EntryPoint>]
let main argv =
    try
        match List.ofArray argv with
        | "emit" :: rest -> emit rest; 0
        | _ -> eprintfn "%s" usage; 2
    with error ->
        eprintfn "%s" error.Message
        1
